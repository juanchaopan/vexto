// The terms of use page (.docs/design/terms.md and screens.md, 使用条款). The first time, the
// person accepts the current version with I agree or logs out; opened from the account menu the
// page is read-only, with a close button and the date of the acceptance instead of the buttons.
import Link from 'next/link';
import { sharedConfig } from '../../../lib/config/shared-config.ts';
import { formatDate } from '../../../lib/format/time-text.ts';
import { Button } from '../../../lib/ui/button.tsx';
import { Icon } from '../../../lib/ui/icon.tsx';
import { licenseBlocks, restrictionsOf } from '../domain/license-blocks.ts';
import { MODEL_LICENSE_TEXT } from '../domain/model-license.ts';
import { termsDateText } from '../domain/terms.ts';
import { DocBody, DocPage } from './doc-page.tsx';

const restrictions = restrictionsOf(licenseBlocks(MODEL_LICENSE_TEXT));

export type TermsDocumentProps =
  | {
      mode: 'accept';
      onAgree: () => void;
      agreeing: boolean;
      onLogOut: () => void;
      loggingOut?: boolean;
    }
  | {
      mode: 'read-only';
      acceptedAt: Date;
      onClose: () => void;
    };

function AcceptActions({
  onAgree,
  agreeing,
  onLogOut,
  loggingOut = false,
}: Extract<TermsDocumentProps, { mode: 'accept' }>) {
  return (
    <>
      <Button onClick={onLogOut} disabled={loggingOut}>
        <Icon name={loggingOut ? 'loader-circle' : 'log-out'} spin={loggingOut} />
        Log out
      </Button>
      <Button variant="primary" onClick={onAgree} disabled={agreeing}>
        {agreeing ? <Icon name="loader-circle" spin /> : null}I agree
      </Button>
    </>
  );
}

export function TermsDocument(props: TermsDocumentProps) {
  const readOnly = props.mode === 'read-only';
  const { version, date } = sharedConfig.terms;
  return (
    <DocPage
      close={readOnly ? { label: 'Close terms', onClose: props.onClose } : undefined}
      actions={readOnly ? undefined : <AcceptActions {...props} />}
    >
      <DocBody>
        <h1>Terms of use</h1>
        <p className="text-[11px] text-muted">
          Version {version} · {termsDateText(date)}
        </p>
        {readOnly ? (
          <p className="text-[11px] text-muted">Accepted {formatDate(props.acceptedAt)}.</p>
        ) : null}
        <p>
          {readOnly
            ? 'You accepted these terms to use vexto.'
            : 'Please read and accept these terms to use vexto.'}
        </p>
        <h2>The voice is AI-generated</h2>
        <p>
          Every voice in vexto, for articles, words and example sentences, is generated by
          Supertonic 3, an AI text-to-speech model. Supertonic 3 is licensed under the BigScience
          Open RAIL-M License.
        </p>
        <Link
          href="/license"
          className="inline-flex min-h-11 items-center gap-1 text-accent underline"
        >
          <Icon name="scale" />
          Read the full license
        </Link>
        <h2>Use restrictions</h2>
        <p>
          The license requires everyone who uses the model to follow its use restrictions
          (Attachment A). By using vexto, you agree to them:
        </p>
        <p>{restrictions.intro}</p>
        <ol className="my-2 grid list-none gap-1.5 p-0">
          {restrictions.items.map((item) => (
            <li key={item.letter} className="grid grid-cols-[28px_minmax(0,1fr)]">
              <span>{item.letter}</span>
              <span>{item.text}</span>
            </li>
          ))}
        </ol>
        <h2>Sharing audio</h2>
        <p>If you share audio from vexto, state clearly that it is machine-generated.</p>
        <h2>Articles</h2>
        <p>
          Articles come from public sources and are provided for language learning only. They are
          not medical advice.
        </p>
      </DocBody>
    </DocPage>
  );
}
